"""Build content/sources.json: the PUBLIC catalog of citable sources.

Usage: python scripts/build_source_catalog.py      (needs local extracts from `python -m ingest`)

It holds only facts about each book (title, authors, licence, official link, page count, chapter and
section headings with their pages, printed-page offset) and no book text, so it is committed and
lets CI check every citation's page range and section without access to the PDFs. Only sources the
manifest clears for internal extraction, whose extract matches the manifest's sha256, are included.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "docs" / "audit" / "source_manifest.json"
EXTRACTS = ROOT / "sources" / "extracts"
OUT = ROOT / "content" / "sources.json"            # bundled into the site: bibliographic facts only
SECTIONS_OUT = ROOT / "content" / "source_sections.json"  # build-time only: headings + pages for citation checks

# Bibliographic facts, checked by hand against each book's official site on 2026-11-08.
INFO = {
    "pch-think-python-2nd": {
        "title": "Think Python: How to Think Like a Computer Scientist (2nd edition)",
        "short": "Think Python 2e",
        "authors": ["Allen B. Downey"],
        "license": "CC BY-NC 3.0",
        "license_url": "https://creativecommons.org/licenses/by-nc/3.0/",
        "official_url": "https://greenteapress.com/wp/think-python-2e/",
    },
    "pch-diveintopython3": {
        "title": "Dive Into Python 3",
        "short": "Dive Into Python 3",
        "authors": ["Mark Pilgrim"],
        "license": "CC BY-SA 3.0",
        "license_url": "https://creativecommons.org/licenses/by-sa/3.0/",
        "official_url": "https://diveintopython3.net/",
    },
    "pch-automate-the-boring-stuff-with-python": {
        "title": "Automate the Boring Stuff with Python",
        "short": "Automate the Boring Stuff",
        "authors": ["Al Sweigart"],
        "license": "CC BY-NC-SA 3.0",
        "license_url": "https://creativecommons.org/licenses/by-nc-sa/3.0/",
        "official_url": "https://automatetheboringstuff.com/",
    },
}


def label_offset(pages: list[dict]) -> tuple[int | None, int | None]:
    """If printed labels equal (physical page - k) for every page from some page onward, return (k, first page)."""
    for start, rec in enumerate(pages):
        lab = rec.get("label")
        if lab and lab.isdigit():
            k = rec["page"] - int(lab)
            if all(r.get("label") == str(r["page"] - k) for r in pages[start:]):
                return k, rec["page"]
            return None, None
    return None, None


def build() -> tuple[dict, dict]:
    manifest = {s["source_id"]: s for s in json.loads(MANIFEST.read_text())["sources"]}
    catalog: dict[str, dict] = {}
    sections: dict[str, list] = {}
    for sid, info in INFO.items():
        src = manifest.get(sid)
        if not (src and src.get("allowed_for_internal_extraction") and src.get("downloaded")):
            continue
        meta_p, pages_p = EXTRACTS / sid / "meta.json", EXTRACTS / sid / "pages.jsonl"
        if not meta_p.is_file():
            print(f"· {sid}: no extract yet, skipped (run: python -m ingest --only {sid})")
            continue
        meta = json.loads(meta_p.read_text())
        if meta["sha256"] != src["sha256"]:
            raise SystemExit(f"✗ {sid}: extract sha256 does not match the manifest; re-extract")
        pages = [json.loads(line) for line in pages_p.read_text().splitlines()]
        k, first = label_offset(pages)
        catalog[sid] = {
            **info,
            "sha256": src["sha256"],
            "page_count": meta["page_count"],
            "page_label_offset": k,
            "page_label_from": first,
        }
        sections[sid] = [[lvl, title.strip(), page] for lvl, title, page in meta["toc"] if lvl <= 4]
    return catalog, sections


def main() -> int:
    catalog, sections = build()
    note = "Generated by scripts/build_source_catalog.py. Facts only; no book text."
    OUT.write_text(json.dumps({"_note": note, "sources": catalog}, indent=1, ensure_ascii=False) + "\n")
    SECTIONS_OUT.write_text(json.dumps({"_note": note, "sections": sections}, ensure_ascii=False) + "\n")
    print(f"✓ wrote {OUT.relative_to(ROOT)} and {SECTIONS_OUT.relative_to(ROOT)}: {len(catalog)} source(s): {', '.join(catalog)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
