"""Verbatim-copy detection against the cited books.

Lessons and the built site must be original prose and code that *cite* books, never copy them. We compare word
n-grams ("shingles") of the text being checked with the books: any shared run of SHINGLE consecutive normalised
words is reported.

Two interchangeable indexes:
  * ExtractIndex: built from the internal extracts in sources/extracts/ (gitignored; owner's machine only).
    It reports the book page a copied phrase came from.
  * HashedIndex: content/provenance/shingles.bin, the sorted set of 48-bit BLAKE2b hashes of every shingle in
    every extract. It contains no book text and cannot be turned back into text, so it is committed. CI
    uses it to scan the exact artifact it deploys. A local build with extracts regenerates it.
content/provenance/** is on the orchestrator's always-denied list: agents cannot alter the evidence.
"""

from __future__ import annotations

import bisect
import hashlib
import json
import os
import re
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# PI_EXTRACTS lets agent worktrees (which have no sources/) point at the owner's extracts, read-only.
EXTRACTS = Path(os.environ.get("PI_EXTRACTS") or ROOT / "sources" / "extracts")
HASHED_DIR = ROOT / "content" / "provenance"
SHINGLE = 12
HASH_BYTES = 6
_PERSON = b"pi-shingle-v1"
_WORD = re.compile(r"[a-z0-9_]+")
# Fixed-width \uXXXX takes exactly 4 hex digits; braced \u{...} up to 6; \xXX exactly 2.
_ESCAPE = re.compile(r"\\(?:u\{([0-9a-fA-F]{1,6})\}|u([0-9a-fA-F]{4})|x([0-9a-fA-F]{2})|([nrtbfv0])|(['\"`\\/]))")


def unescape_js(text: str) -> str:
    """Decode string-literal escapes found in bundled JS/JSON so copied prose can't hide behind them."""
    def sub(m: re.Match) -> str:
        code = m.group(1) or m.group(2) or m.group(3)
        if code:
            cp = int(code, 16)
            return chr(cp) if cp <= 0x10FFFF else " "
        return " " if m.group(4) else m.group(5)
    return _ESCAPE.sub(sub, text)


def words(text: str) -> list[str]:
    return _WORD.findall(text.lower())


def shingles(ws: list[str], n: int = SHINGLE):
    for i in range(len(ws) - n + 1):
        yield " ".join(ws[i:i + n])


def shingle_hash(sh: str) -> bytes:
    return hashlib.blake2b(sh.encode("utf-8"), digest_size=HASH_BYTES, person=_PERSON).digest()


@dataclass(frozen=True)
class Match:
    source_id: str
    page: int | None
    phrase: str

    def where(self) -> str:
        return f"{self.source_id} page {self.page}" if self.page else "a cited book (hashed index)"


class ExtractIndex:
    """Maps each shingle of the local extracts to its first (source_id, page)."""

    def __init__(self, root: Path = EXTRACTS, n: int = SHINGLE):
        self.n = n
        self.index: dict[str, tuple[str, int]] = {}
        self.sources: list[str] = []
        self.shas: dict[str, str] = {}  # source_id -> sha256 of the PDF the extract came from
        if not root.is_dir():
            return
        for pages in sorted(root.glob("*/pages.jsonl")):
            sid = pages.parent.name
            self.sources.append(sid)
            meta = pages.parent / "meta.json"
            if meta.is_file():
                self.shas[sid] = json.loads(meta.read_text(encoding="utf-8"))["sha256"]
            for line in pages.read_text(encoding="utf-8").splitlines():
                rec = json.loads(line)
                for sh in shingles(words(rec["text"]), n):
                    self.index.setdefault(sh, (sid, rec["page"]))

    @property
    def available(self) -> bool:
        return bool(self.index)

    def find(self, text: str, limit: int = 3) -> list[Match]:
        out: list[Match] = []
        seen_pages: set[tuple[str, int]] = set()
        for sh in shingles(words(text), self.n):
            hit = self.index.get(sh)
            if hit and hit not in seen_pages:
                seen_pages.add(hit)
                out.append(Match(hit[0], hit[1], sh))
                if len(out) >= limit:
                    break
        return out

    def hashed_blob(self) -> bytes:
        return b"".join(sorted({shingle_hash(sh) for sh in self.index}))

    def hashed_meta(self, blob: bytes) -> dict:
        return {"_note": "Generated by scripts/validate_content.py from local extracts. Hashes only; no book text.",
                "shingle_words": self.n, "hash": f"blake2b-{HASH_BYTES * 8}/{_PERSON.decode()}",
                "count": len(blob) // HASH_BYTES, "blob_sha256": hashlib.sha256(blob).hexdigest(),
                "extracts": dict(sorted(self.shas.items()))}


class HashedIndex:
    """Membership-only index over hashed shingles (committed; usable without book text, e.g. in CI)."""

    def __init__(self, root: Path = HASHED_DIR):
        self.meta: dict = {}
        self.blob = b""
        self.error: str | None = None
        self.n = SHINGLE
        self.shas: dict[str, str] = {}
        self.sources: list[str] = []
        meta, blob = root / "index.json", root / "shingles.bin"
        if not (meta.is_file() and blob.is_file()):
            self.error = f"no hashed copy index at {root}"
            return
        self.meta, self.blob = json.loads(meta.read_text()), blob.read_bytes()
        if hashlib.sha256(self.blob).hexdigest() != self.meta.get("blob_sha256"):
            self.error, self.blob = "shingles.bin does not match index.json (blob_sha256)", b""
        elif self.meta.get("shingle_words") != SHINGLE or len(self.blob) % HASH_BYTES:
            self.error, self.blob = "hashed index was built with different parameters", b""
        self.shas = self.meta.get("extracts", {})
        self.sources = sorted(self.shas)

    @property
    def available(self) -> bool:
        return bool(self.blob)

    def __contains__(self, h: bytes) -> bool:
        k, w = len(self.blob) // HASH_BYTES, HASH_BYTES
        i = bisect.bisect_left(range(k), h, key=lambda j: self.blob[j * w:(j + 1) * w])
        return i < k and self.blob[i * w:(i + 1) * w] == h

    def find(self, text: str, limit: int = 3) -> list[Match]:
        out = []
        for sh in shingles(words(text), SHINGLE):
            if shingle_hash(sh) in self:
                out.append(Match("(hashed)", None, sh))
                if len(out) >= limit:
                    break
        return out


def write_hashed_index(index: ExtractIndex, root: Path = HASHED_DIR) -> bool:
    """Regenerate the committed hashed index from local extracts. Returns True if it changed."""
    blob = index.hashed_blob()
    meta = index.hashed_meta(blob)
    root.mkdir(parents=True, exist_ok=True)
    mp, bp = root / "index.json", root / "shingles.bin"
    if mp.is_file() and bp.is_file() and json.loads(mp.read_text()) == meta and bp.read_bytes() == blob:
        return False
    bp.write_bytes(blob)
    mp.write_text(json.dumps(meta, indent=1) + "\n")
    return True


def load_index() -> ExtractIndex | HashedIndex:
    """Local extracts when present (exact pages), else the committed hashed index."""
    ex = ExtractIndex()
    return ex if ex.available else HashedIndex()


def strings_in(obj) -> list[str]:
    """Every string value in a JSON-like object, in document order."""
    if isinstance(obj, str):
        return [obj]
    if isinstance(obj, dict):
        return [s for v in obj.values() for s in strings_in(v)]
    if isinstance(obj, list):
        return [s for v in obj for s in strings_in(v)]
    return []
